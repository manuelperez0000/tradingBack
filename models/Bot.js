import pool from "../config/database.js";

const botFields = `
  id, nombre, profit_factor, win_rate, profit_1_year, drawdown,
   imagen, descripcion, created_at, updated_at
`;

function toBot(bot) {
  return {
    ...bot,
    profit_factor: Number(bot.profit_factor),
    win_rate: Number(bot.win_rate),
    profit_1_year: Number(bot.profit_1_year),
    drawdown: Number(bot.drawdown)
  };
}

export async function initializeBotTable() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS bots (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nombre VARCHAR(200) NOT NULL,
      profit_factor NUMERIC NOT NULL CHECK (profit_factor >= 0),
      win_rate NUMERIC NOT NULL CHECK (win_rate BETWEEN 0 AND 100),
      profit_1_year NUMERIC NOT NULL,
      drawdown NUMERIC NOT NULL CHECK (drawdown >= 0),
      imagen TEXT NOT NULL,
      descripcion TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await pool.query(`
    ALTER TABLE bots
    DROP COLUMN IF EXISTS precio_mensual,
    DROP COLUMN IF EXISTS moneda
  `);
}

export async function createBot(botData) {
  const { rows } = await pool.query(
    `INSERT INTO bots (
       nombre, profit_factor, win_rate, profit_1_year, drawdown,
       imagen, descripcion
     )
     VALUES ($1, $2, $3, $4, $5, $6, $7)
     RETURNING ${botFields}`,
    [
      botData.nombre,
      botData.profit_factor,
      botData.win_rate,
      botData.profit_1_year,
      botData.drawdown,
      botData.imagen,
      botData.descripcion,
    ],
  );
  return toBot(rows[0]);
}

export async function listBots() {
  const { rows } = await pool.query(
    `SELECT ${botFields}
     FROM bots
     ORDER BY created_at DESC, id DESC`,
  );
  return rows.map(toBot);
}

export async function findBotById(id) {
  const { rows } = await pool.query(
    `SELECT ${botFields}
     FROM bots
     WHERE id = $1`,
    [id],
  );
  return rows[0] ? toBot(rows[0]) : null;
}

export async function updateBot(id, botData) {
  const { rows } = await pool.query(
    `UPDATE bots
     SET nombre = $2,
         profit_factor = $3,
         win_rate = $4,
         profit_1_year = $5,
         drawdown = $6,
         imagen = $7,
         descripcion = $8,
         updated_at = NOW()
     WHERE id = $1
     RETURNING ${botFields}`,
    [
      id,
      botData.nombre,
      botData.profit_factor,
      botData.win_rate,
      botData.profit_1_year,
      botData.drawdown,
      botData.imagen,
      botData.descripcion,
    ],
  );
  return rows[0] ? toBot(rows[0]) : null;
}

export async function deleteBot(id) {
  const { rows } = await pool.query(
    `DELETE FROM bots
     WHERE id = $1
     RETURNING ${botFields}`,
    [id],
  );
  return rows[0] ? toBot(rows[0]) : null;
}
